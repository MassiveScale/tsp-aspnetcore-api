import { deepStrictEqual, ok } from "node:assert";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, it } from "node:test";
import { NodeHost, compile, resolvePath } from "@typespec/compiler";
import { createTester, resolveVirtualPath } from "@typespec/compiler/testing";
import { MANIFEST_FILE_NAME } from "../src/clean.js";

const EMITTER = "@massivescale/tsp-aspnetcore-api";

const tester = createTester(resolvePath(import.meta.dirname, "../.."), {
  libraries: [EMITTER, "@typespec/http", "@typespec/versioning"],
});

/** Absolute path of the emitter output directory inside the virtual file system. */
const OUTPUT_DIR = resolveVirtualPath(resolvePath("tsp-output", EMITTER));

/** Header carrying the emitter signature written by the default `file` template. */
const GENERATED_HEADER = `//-----------------------------------------------------------------------
// <copyright file="seed.g.cs" />
//
// This file is AUTO-GENERATED by @massivescale/tsp-aspnetcore-api. Do not edit this file directly.
// <auto-generated />
//-----------------------------------------------------------------------
namespace Demo.Models { public partial class Seed { } }
`;

const MODEL = `
  namespace Demo;
  model User { id: string; }
`;

/** Absolute path of a file in the virtual emitter output directory. */
function outputPath(...segments: string[]): string {
  return resolvePath(OUTPUT_DIR, ...segments);
}

/** Writes a custom template to a real temp file and returns its path. */
function writeTemplate(name: string, content: string): string {
  const dir = mkdtempSync(join(tmpdir(), "tsp-aspnetcore-clean-"));
  const path = join(dir, name);
  writeFileSync(path, content, "utf-8");
  return path;
}

describe("csharp emitter - clean-output-dirs", () => {
  it("removes a stale generated file (marker present) before emitting", async () => {
    const instance = await tester.emit(EMITTER).createInstance();
    instance.fs.add(
      resolvePath(OUTPUT_DIR, "Models", "Stale.g.cs"),
      GENERATED_HEADER,
    );

    const [result] = await instance.compileAndDiagnose(MODEL);

    ok(
      result.outputs["Models/User.g.cs"],
      "expected the current model to be emitted",
    );
    ok(
      result.outputs["Models/Stale.g.cs"] === undefined,
      "stale generated file should have been removed before emit",
    );
  });

  it("leaves a non-generated file behind and warns when it lacks the marker", async () => {
    const instance = await tester.emit(EMITTER).createInstance();
    // Matches the generated extension but has no emitter signature.
    instance.fs.add(
      resolvePath(OUTPUT_DIR, "Models", "Handwritten.g.cs"),
      "namespace Demo.Models { public partial class Handwritten { } }\n",
    );
    // Does not match the generated extension at all.
    instance.fs.add(
      resolvePath(OUTPUT_DIR, "Models", "Keep.cs"),
      "namespace Demo.Models { public class Keep { } }\n",
    );

    const [result, diagnostics] = await instance.compileAndDiagnose(MODEL);

    ok(
      result.outputs["Models/Handwritten.g.cs"],
      "extension-matching file without marker must be left behind",
    );
    ok(
      result.outputs["Models/Keep.cs"],
      "non-generated-extension file must be left behind",
    );

    const warning = diagnostics.find(
      (d) => d.code === `${EMITTER}/output-file-left-behind`,
    );
    ok(
      warning,
      `expected output-file-left-behind warning, got: ${JSON.stringify(diagnostics)}`,
    );
    ok(
      warning.message.includes("Handwritten.g.cs"),
      `warning should name the retained file: ${warning.message}`,
    );
    // The plain `.cs` file is not a removal candidate, so it must not warn.
    ok(
      !warning.message.includes("Keep.cs"),
      `plain .cs files should not be reported: ${warning.message}`,
    );
  });

  it("does not touch the output directory when clean-output-dirs is false", async () => {
    const instance = await tester
      .emit(EMITTER, { "clean-output-dirs": false })
      .createInstance();
    instance.fs.add(
      resolvePath(OUTPUT_DIR, "Models", "Stale.g.cs"),
      GENERATED_HEADER,
    );

    const [result, diagnostics] = await instance.compileAndDiagnose(MODEL);

    ok(
      result.outputs["Models/Stale.g.cs"],
      "stale file must be preserved when cleaning is disabled",
    );
    ok(
      !diagnostics.some((d) => d.code === `${EMITTER}/output-file-left-behind`),
      "no left-behind warning should be emitted when cleaning is disabled",
    );
  });
  it("keeps other generators' <auto-generated> files when the output dir is a project root", async () => {
    const instance = await tester
      .emit(EMITTER, { "models-output-dir": ".", "file-extension": ".cs" })
      .createInstance();
    instance.fs.add(
      outputPath("obj", "Debug", "App.GlobalUsings.g.cs"),
      "// <auto-generated/>\nglobal using System;\n",
    );
    instance.fs.add(
      outputPath("Migrations", "20240101_Init.Designer.cs"),
      "// <auto-generated />\nnamespace App.Migrations;\n",
    );
    instance.fs.add(
      outputPath("Clients", "ApiClient.cs"),
      "// <auto-generated>\n// Generated by another tool.\n// </auto-generated>\n",
    );

    const [result] = await instance.compileAndDiagnose(MODEL);

    ok(result.outputs["User.cs"], "expected the model to be emitted");
    for (const path of [
      "obj/Debug/App.GlobalUsings.g.cs",
      "Migrations/20240101_Init.Designer.cs",
      "Clients/ApiClient.cs",
    ]) {
      ok(result.outputs[path], `${path} must survive cleanup`);
    }
  });

  it("only trusts the emitter signature in the first lines of a file", async () => {
    const instance = await tester.emit(EMITTER).createInstance();
    const late = `namespace Demo;\n${"\n".repeat(20)}// <auto-generated /> auto-generated by @massivescale/tsp-aspnetcore-api\n`;
    instance.fs.add(outputPath("Models", "Late.g.cs"), late);

    const [result, diagnostics] = await instance.compileAndDiagnose(MODEL);

    ok(result.outputs["Models/Late.g.cs"], "a late signature must not count");
    ok(
      diagnostics.some((d) => d.message.includes("Late.g.cs")),
      "the retained file should be reported",
    );
  });

  it("removes files written by the 1.0.0-beta file template", async () => {
    const instance = await tester.emit(EMITTER).createInstance();
    instance.fs.add(
      outputPath("Models", "Old.g.cs"),
      [
        "//-----------------------------------------------------------------------",
        '// <copyright file="Old.g.cs" />',
        "//",
        "// This file is AUTO-GENERATED. Do not edit this file directly.",
        "// <auto-generated />",
        "//-----------------------------------------------------------------------",
        "",
      ].join("\n"),
    );

    const [result] = await instance.compileAndDiagnose(MODEL);

    ok(result.outputs["Models/Old.g.cs"] === undefined, "legacy file removed");
  });

  it("never scans bin, obj, node_modules or dot-folders", async () => {
    const skipped = ["bin", "obj", "node_modules", ".git"];
    const instance = await tester.emit(EMITTER).createInstance();
    for (const dir of skipped) {
      instance.fs.add(outputPath("Models", dir, "Kept.g.cs"), GENERATED_HEADER);
    }

    const [result] = await instance.compileAndDiagnose(MODEL);

    for (const dir of skipped) {
      ok(
        result.outputs[`Models/${dir}/Kept.g.cs`],
        `Models/${dir} must not be scanned`,
      );
    }
  });

  it("writes a manifest and removes exactly the files it lists on the next run", async () => {
    // A custom file template without the signature: only the manifest can
    // identify its output as generated.
    const fileTemplate = writeTemplate(
      "file.hbs",
      "namespace {{namespace}}\n{\n{{indent body}}\n}\n",
    );
    const instance = await tester
      .emit(EMITTER, { templates: { file: fileTemplate } })
      .createInstance();

    const [first] = await instance.compileAndDiagnose(MODEL);
    ok(first.outputs["Models/User.g.cs"], "first run emits User");
    const manifest = JSON.parse(first.outputs[MANIFEST_FILE_NAME]) as {
      version: number;
      files: string[];
    };
    ok(
      manifest.files.includes("Models/User.g.cs"),
      `manifest should list Models/User.g.cs: ${JSON.stringify(manifest)}`,
    );

    const [second, diagnostics] = await instance.compileAndDiagnose(`
      namespace Demo;
      model Account { id: string; }
    `);

    ok(second.outputs["Models/Account.g.cs"], "second run emits Account");
    ok(
      second.outputs["Models/User.g.cs"] === undefined,
      "User.g.cs from the previous run must be removed via the manifest",
    );
    ok(
      !diagnostics.some((d) => d.code === `${EMITTER}/output-file-left-behind`),
      "manifest-driven cleanup must not warn",
    );
  });

  it("ignores manifest entries outside the output dirs or without the extension", async () => {
    const instance = await tester.emit(EMITTER).createInstance();
    const outside = resolvePath(OUTPUT_DIR, "..", "Outside.g.cs");
    instance.fs.add(
      resolvePath(OUTPUT_DIR, MANIFEST_FILE_NAME),
      JSON.stringify({
        version: 1,
        files: ["../Outside.g.cs", "Models/Notes.txt", "Models/Stale.g.cs"],
      }),
    );
    instance.fs.add(outside, "x");
    instance.fs.add(outputPath("Models", "Notes.txt"), "x");
    instance.fs.add(outputPath("Models", "Stale.g.cs"), "x");

    await instance.compileAndDiagnose(MODEL);

    ok(instance.fs.fs.has(outside), "a path outside the output dirs is kept");
    ok(
      instance.fs.fs.has(outputPath("Models", "Notes.txt")),
      "a path without the generated extension is kept",
    );
    ok(
      !instance.fs.fs.has(outputPath("Models", "Stale.g.cs")),
      "a listed generated file is removed even without a signature",
    );
  });

  it("does not write a manifest when clean-output-dirs is false", async () => {
    const [result] = await tester
      .emit(EMITTER, { "clean-output-dirs": false })
      .compileAndDiagnose(MODEL);

    ok(result.outputs[MANIFEST_FILE_NAME] === undefined);
  });

  it("rejects an empty or malformed file-extension", async () => {
    for (const extension of ["", ".", "cs", ".g/cs"]) {
      const [result, diagnostics] = await tester
        .emit(EMITTER, { "file-extension": extension })
        .compileAndDiagnose(MODEL);

      ok(
        diagnostics.some(
          (d) => d.severity === "error" && d.message.includes("file-extension"),
        ),
        `expected an error for "${extension}", got: ${JSON.stringify(diagnostics.map((d) => d.message))}`,
      );
      deepStrictEqual(Object.keys(result.outputs), []);
    }
  });

  it("does not clean when a custom template fails to compile", async () => {
    const classTemplate = writeTemplate("class.hbs", "{{#if className}\n");
    const instance = await tester
      .emit(EMITTER, { templates: { class: classTemplate } })
      .createInstance();
    instance.fs.add(outputPath("Models", "Stale.g.cs"), GENERATED_HEADER);

    const [result, diagnostics] = await instance.compileAndDiagnose(MODEL);

    const failure = diagnostics.find(
      (d) => d.code === `${EMITTER}/template-load-failed`,
    );
    ok(
      failure,
      `expected template-load-failed: ${JSON.stringify(diagnostics)}`,
    );
    ok(failure.message.includes('"class"'), failure.message);
    ok(
      result.outputs["Models/Stale.g.cs"],
      "existing output must be kept when the renderer cannot be built",
    );
  });

  it("does not clean when a custom validator template fails to compile", async () => {
    const postTemplate = writeTemplate("validator-post.hbs", "{{/each}}\n");
    const instance = await tester
      .emit(EMITTER, {
        "emit-validators": true,
        templates: { "validator-post": postTemplate },
      })
      .createInstance();
    instance.fs.add(outputPath("Models", "Stale.g.cs"), GENERATED_HEADER);

    const [result, diagnostics] = await instance.compileAndDiagnose(MODEL);

    const failure = diagnostics.find(
      (d) => d.code === `${EMITTER}/template-load-failed`,
    );
    ok(
      failure,
      `expected template-load-failed: ${JSON.stringify(diagnostics)}`,
    );
    ok(failure.message.includes('"validator-post"'), failure.message);
    ok(result.outputs["Models/Stale.g.cs"], "existing output must be kept");
  });
});

describe("csharp emitter - clean-output-dirs on the real file system", () => {
  it("does not follow a link or junction out of the output dir", async () => {
    const root = mkdtempSync(join(tmpdir(), "tsp-aspnetcore-links-"));
    try {
      const out = join(root, "out");
      const outside = join(root, "outside");
      mkdirSync(out, { recursive: true });
      mkdirSync(outside, { recursive: true });
      const victim = join(outside, "Victim.g.cs");
      writeFileSync(
        victim,
        "// auto-generated by @massivescale/tsp-aspnetcore-api\n",
      );
      // A junction needs no elevation on Windows; elsewhere it is a symlink.
      symlinkSync(outside, join(out, "Linked"), "junction");
      writeFileSync(join(root, "main.tsp"), MODEL);

      const program = await compile(NodeHost, join(root, "main.tsp"), {
        emit: [resolvePath(import.meta.dirname, "../..")],
        options: {
          [EMITTER]: { "emitter-output-dir": out, "models-output-dir": "." },
        },
      });

      deepStrictEqual(
        program.diagnostics.map((d) => d.message),
        [],
      );
      ok(
        existsSync(join(out, "User.g.cs")),
        "expected the model to be emitted",
      );
      ok(existsSync(victim), "a file behind a link must never be deleted");
      ok(
        readFileSync(join(out, MANIFEST_FILE_NAME), "utf-8").includes(
          '"User.g.cs"',
        ),
        "manifest should list the emitted file",
      );
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
